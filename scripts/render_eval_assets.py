#!/usr/bin/env python3
"""Render eval chart SVG + Markdown tables from evals/baselines/latest.json."""

from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASELINE = ROOT / "evals" / "baselines" / "latest.json"
OUT_SVG = ROOT / "docs" / "assets" / "eval-results.svg"
OUT_SNIPPET = ROOT / "docs" / "assets" / "eval-results.snippet.md"


def _score(r: dict) -> float:
    if r.get("combined_score") is not None:
        return float(r["combined_score"])
    return float(r.get("keyword_score") or 0.0)


def _passed(r: dict) -> bool:
    if r.get("status") != "success":
        return False
    return _score(r) >= 0.5 and bool(r.get("length_ok"))


def load_baseline() -> dict:
    return json.loads(BASELINE.read_text(encoding="utf-8"))


_LAYER_ALIASES = {
    "mgmt": "management",
    "ops": "operations",
}


def layer_averages(results: list[dict]) -> dict[str, float]:
    buckets: dict[str, list[float]] = defaultdict(list)
    for r in results:
        if r.get("status") != "success":
            continue
        if r.get("mode") == "swarm":
            continue  # swarm tasks span layers; chart is per-domain single-agent
        layer = _LAYER_ALIASES.get(str(r.get("layer") or "unknown"), str(r.get("layer") or "unknown"))
        buckets[layer].append(_score(r))
    return {k: statistics.fmean(v) for k, v in sorted(buckets.items()) if v}


def render_svg(layer_avgs: dict[str, float], meta: dict, singles_pass: str, swarm_pass: str) -> str:
    width, height = 960, 420
    margin_l, margin_b, margin_t = 120, 60, 70
    chart_w = width - margin_l - 40
    chart_h = height - margin_t - margin_b
    layers = list(layer_avgs.keys())
    n = max(1, len(layers))
    bar_w = min(80, chart_w / n * 0.7)
    gap = chart_w / n

    bars = []
    for i, layer in enumerate(layers):
        val = layer_avgs[layer]
        bh = chart_h * val
        x = margin_l + i * gap + (gap - bar_w) / 2
        y = margin_t + chart_h - bh
        bars.append(
            f'<rect x="{x:.1f}" y="{y:.1f}" width="{bar_w:.1f}" height="{bh:.1f}" '
            f'rx="4" fill="#ffd900"/>'
            f'<text x="{x + bar_w / 2:.1f}" y="{y - 8:.1f}" text-anchor="middle" '
            f'font-family="ui-sans-serif,system-ui,sans-serif" font-size="11" '
            f'font-weight="700" fill="#0a0a0a">{val:.2f}</text>'
            f'<text x="{x + bar_w / 2:.1f}" y="{height - 28}" text-anchor="middle" '
            f'font-family="ui-sans-serif,system-ui,sans-serif" font-size="11" '
            f'fill="#525252">{layer}</text>'
        )

    spent = meta.get("budget_spent_usd", 0)
    limit = meta.get("budget_limit_usd", 5)
    passed = meta.get("passed", 0)
    tasks = meta.get("task_count", 0)
    provider = meta.get("provider", "n/a")
    model = meta.get("model_sonnet", "n/a")

    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" role="img" aria-label="Eval results by layer">
  <title>Swarm 357 eval results</title>
  <rect width="{width}" height="{height}" fill="#fafafa"/>
  <text x="40" y="36" font-family="ui-sans-serif,system-ui,sans-serif" font-size="20" font-weight="700" fill="#0a0a0a">Eval results by layer</text>
  <text x="40" y="56" font-family="ui-sans-serif,system-ui,sans-serif" font-size="12" fill="#737373">{passed}/{tasks} passed · ${spent:.2f}/${limit:.2f} · {provider} · {model}</text>
  <text x="40" y="74" font-family="ui-sans-serif,system-ui,sans-serif" font-size="11" fill="#525252">Singles {singles_pass} · Swarm {swarm_pass} (timeouts reported honestly)</text>
  <line x1="{margin_l}" y1="{margin_t}" x2="{margin_l}" y2="{margin_t + chart_h}" stroke="#e5e5e5" stroke-width="2"/>
  <line x1="{margin_l}" y1="{margin_t + chart_h}" x2="{width - 40}" y2="{margin_t + chart_h}" stroke="#e5e5e5" stroke-width="2"/>
  {"".join(bars)}
</svg>
"""


def render_snippet(meta: dict, results: list[dict], layer_avgs: dict[str, float]) -> str:
    singles = [r for r in results if r.get("mode") == "single"]
    swarms = [r for r in results if r.get("mode") == "swarm"]
    s_ok = sum(1 for r in singles if _passed(r))
    w_ok = sum(1 for r in swarms if _passed(r))
    scored = [_score(r) for r in results if r.get("status") == "success"]
    avg = statistics.fmean(scored) if scored else 0.0
    catalog = [
        r
        for r in results
        if "-burn" not in r.get("task_id", "")
        and "-retry" not in r.get("task_id", "")
        and "-stress" not in r.get("task_id", "")
    ]
    catalog_ok = sum(1 for r in catalog if _passed(r))

    layer_rows = "\n".join(
        f"| {layer} | {avg:.2f} |" for layer, avg in layer_avgs.items()
    )
    return f"""<!-- generated by scripts/render_eval_assets.py, do not edit by hand -->

| Metric | Value |
|--------|------:|
| Executions | {meta.get("task_count", 0)} |
| Passed gates | {meta.get("passed", 0)} |
| Avg combined score | {avg:.3f} |
| Spend | ${float(meta.get("budget_spent_usd", 0)):.4f} / ${float(meta.get("budget_limit_usd", 5)):.2f} |
| Provider | `{meta.get("provider", "")}` |
| Agent model | `{meta.get("model_sonnet", "")}` |
| Single-agent pass | {s_ok}/{len(singles)} |
| Swarm pass | {w_ok}/{len(swarms)} |
| Catalog (non-burn) pass | {catalog_ok}/{len(catalog)} |

### Per-layer average combined score

| Layer | Avg score |
|-------|----------:|
{layer_rows}

**Known limitation:** swarm pipeline tasks may hit 150-180s wall-clock timeouts on OpenRouter; single-agent + tools is the production demo path.
"""


def main() -> None:
    data = load_baseline()
    meta = data.get("meta") or {}
    results = data.get("results") or []
    layer_avgs = layer_averages(results)
    singles = [r for r in results if r.get("mode") == "single"]
    swarms = [r for r in results if r.get("mode") == "swarm"]
    s_pass = f"{sum(1 for r in singles if _passed(r))}/{len(singles)}"
    w_pass = f"{sum(1 for r in swarms if _passed(r))}/{len(swarms)}"

    OUT_SVG.parent.mkdir(parents=True, exist_ok=True)
    OUT_SVG.write_text(render_svg(layer_avgs, meta, s_pass, w_pass), encoding="utf-8")
    OUT_SNIPPET.write_text(render_snippet(meta, results, layer_avgs), encoding="utf-8")
    print(f"Wrote {OUT_SVG.relative_to(ROOT)}")
    print(f"Wrote {OUT_SNIPPET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
